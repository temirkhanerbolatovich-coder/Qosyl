export function localizedProjectTemplates(locale: Locale): readonly ProjectTemplate[] {
  if (locale === 'ru') return projectTemplates;
  return projectTemplates.map((template) => ({
    ...template,
    name: projectTemplatesKk[template.id].name,
    fields: { ...template.fields, ...projectTemplatesKk[template.id].fields },
  }));
}

/** Template application is local and fills blanks only; authored values always take precedence. */
export function getProjectTemplatePatch(
  template: ProjectTemplate,
  current: Partial<Record<ProjectTemplateField, string>>,
) {
  const patch: Partial<Record<ProjectTemplateField, string>> = {};
  for (const [name, value] of Object.entries(template.fields)) {
    const field = name as ProjectTemplateField;
    if (!current[field]?.trim()) patch[field] = value;
  }
  return patch;
}
