import { z } from 'zod';

export const notificationLanguageInput = z.strictObject({ language: z.enum(['ru', 'kk']) });
export type NotificationLanguage = z.infer<typeof notificationLanguageInput>['language'];

/** Only system-authored strings are translated; unknown text is retained verbatim. */
export function notificationText(language: NotificationLanguage, text: string): string {
  if (language !== 'kk') return text;
  const messages: Record<string, string> = {
    'Новый отклик на заказ.': 'Тапсырысқа жаңа өтінім түсті.',
    'Вас выбрали. Подтвердите условия перед началом работы.':
      'Сізді таңдады. Жұмысты бастамас бұрын шарттарды растаңыз.',
    'По вашему отклику выбран другой исполнитель.':
      'Сіздің өтініміңіз бойынша басқа орындаушы таңдалды.',
    'Заказ одобрен и опубликован.': 'Тапсырыс мақұлданып, жарияланды.',
    'Профиль заказчика проверен модератором.': 'Тапсырыс берушінің профилін модератор тексерді.',
    'Условия согласованы. Можно приступать к работе.':
      'Шарттар келісілді. Жұмысты бастауға болады.',
    'Предложена новая версия условий. Требуются два подтверждения.':
      'Шарттардың жаңа нұсқасы ұсынылды. Екі тараптың растауы қажет.',
    'Результат сдан. Проверьте критерии приемки.':
      'Нәтиже тапсырылды. Қабылдау өлшемдерін тексеріңіз.',
    'Заказчик запросил исправления по критериям.':
      'Тапсырыс беруші өлшемдер бойынша түзетулер сұрады.',
    'Результат принят. Согласуйте портфолио и закрытие.':
      'Нәтиже қабылданды. Портфолио мен жабу шарттарын келісіңіз.',
    'Статус оплаты оспорен. Обращение поступило модератору; денежные операции платформа не выполняет.':
      'Төлем мәртебесіне дау білдірілді. Өтініш модераторға жіберілді; платформа ақша операцияларын жүргізбейді.',
    'Заказ отменён автором. Ваш отклик закрыт.':
      'Тапсырысты авторы тоқтатты. Сіздің өтініміңіз жабылды.',
  };
  if (Object.hasOwn(messages, text)) return messages[text];
  for (const [prefix, translated] of [
    ['Заказ возвращен: ', 'Тапсырыс қайтарылды: '],
    ['Профиль не подтвержден: ', 'Профиль расталмады: '],
    ['Ответ по жалобе: ', 'Шағымға жауап: '],
    ['Модератор приостановил заказ: ', 'Модератор тапсырысты тоқтатты: '],
    ['Заказ отменён: ', 'Тапсырыс тоқтатылды: '],
  ])
    if (text.startsWith(prefix)) return translated + text.slice(prefix.length);
  return text;
}

export function opportunityNotificationText(language: NotificationLanguage, count: number) {
  return language === 'kk'
    ? `Сақталған іздеу бойынша жаңа мүмкіндіктер: ${count}. Өзекті нәтижелерді ашыңыз.`
    : `Новые возможности по сохранённому поиску: ${count}. Откройте актуальную выдачу.`;
}

export function lifecycleNotificationText(
  language: NotificationLanguage,
  kind: 'expired' | 'publication' | 'execution' | 'review',
  title: string,
  original: string,
) {
  if (language !== 'kk') return original;
  if (kind === 'expired')
    return `«${title}» жарияланған тапсырмасының мерзімі аяқталды. Ашық өтінімдер жабылды; тарих сақталды.`;
  if (kind === 'publication')
    return `«${title}» тапсырмасының жариялануы аяқталғанға дейін бір тәуліктен аспайтын уақыт қалды. Өтінімдер мен шарттардың өзектілігін тексеріңіз.`;
  if (kind === 'review')
    return `«${title}» тапсырмасының нәтижесі кемінде екі тәулік бойы тексеруді күтуде. Оны қабылдаңыз немесе келісілген өлшемдер бойынша нақты ескертулер беріңіз.`;
  return original.startsWith('Согласованный срок')
    ? `«${title}» тапсырмасының келісілген мерзімі аяқталды. Нәтижені тексеріп, келесі әрекеттерді тапсырыс берушімен келісіңіз.`
    : `«${title}» тапсырмасының келісілген мерзіміне дейін бір тәуліктен аспайтын уақыт қалды. Нәтиже мен қабылдау өлшемдерін тексеріңіз.`;
}
