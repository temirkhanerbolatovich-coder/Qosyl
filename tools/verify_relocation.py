"""Verify the cold relocation before restarting or rebuilding generated state."""
import json
from collections import Counter
from plan_reorganization import BASE, ROOT, REPORT, sha

rows = json.loads((REPORT / 'relocation-map.json').read_text(encoding='utf-8'))
edits = {r['path']:r for r in json.loads((REPORT / 'path-edits.json').read_text(encoding='utf-8'))}
cold = json.loads((REPORT / 'cold-state-hashes.json').read_text(encoding='utf-8'))
deleted = json.loads((REPORT / 'deletion-log.json').read_text(encoding='utf-8-sig'))
deleted_paths = {r['old'] for r in deleted}
failures, counts = [], Counter()
generated_changes = []
for row in rows:
    old = row['old']
    if old.startswith(('.git/', '.local/')):
        continue  # Verified against the authoritative stopped-state snapshot below.
    if row['action'] == 'DELETE_DUPLICATE':
        if old not in deleted_paths or (BASE / old).exists():
            failures.append({'path': old, 'reason': 'Deletion record mismatch'})
        else:
            counts['duplicates_removed'] += 1
        continue
    path = BASE / row['new']
    if old.startswith('node_modules/.vite/vitest/') and path.is_file():
        generated_changes.append({'path': row['new'], 'reason': 'Regenerated by the recorded 27-test Vitest run', 'before_sha256': row['sha256'], 'after_sha256': sha(path)})
        counts['test_cache_regenerated'] += 1
        continue
    edit = edits.get(path.relative_to(ROOT).as_posix())
    expected = edit['after_sha256'] if edit else row['sha256']
    if not path.is_file() or sha(path) != expected:
        failures.append({'path': row['new'], 'reason': 'Missing or hash changed'})
    else:
        counts['path_edited' if edit else 'byte_identical'] += 1
for row in cold:
    path = ROOT / row['path']
    if not path.is_file() or sha(path) != row['sha256']:
        failures.append({'path': row['path'], 'reason': 'Cold state mismatch'})
    else:
        counts['cold_state_identical'] += 1
result = {'phase': 'after relocation and link repair, before rebuild/restart', 'counts': dict(counts), 'generated_changes': generated_changes, 'failures': failures, 'passed': not failures}
(REPORT / 'relocation-integrity.json').write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps(result, ensure_ascii=False))
raise SystemExit(0 if result['passed'] else 1)
